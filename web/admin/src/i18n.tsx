export function translateText(text: string, language: AdminLanguage): string {
  if (!text.trim()) return text;
  const value = text.trim();
  const translated = language === 'zh' ? chinese[value] ?? dynamicTranslation(value, language) : english[value] ?? dynamicTranslation(value, language);
  if (!translated) return text;
  return `${text.slice(0, text.indexOf(value))}${translated}${text.slice(text.indexOf(value) + value.length)}`;
}

function currentAdminLanguage(): AdminLanguage {
  const documentLanguage = typeof document === 'undefined' ? '' : document.documentElement.lang.toLowerCase();
  return documentLanguage.startsWith('en') ? 'en'
    : documentLanguage.startsWith('zh') ? 'zh'
      : readPreference(languageKey, ['zh', 'en'], 'zh');
}

export function adminLocale(): 'zh-CN' | 'en-US' {
  return currentAdminLanguage() === 'zh' ? 'zh-CN' : 'en-US';
}

export function confirmAction(message: string): boolean {
  return window.confirm(translateText(message, currentAdminLanguage()));
}

export function translateNode(node: ReactNode, language: AdminLanguage): ReactNode {
  if (typeof node === 'string') return translateText(node, language);
  if (Array.isArray(node)) return Children.map(node, (child) => translateNode(child, language));
  if (!isValidElement<{ children?: ReactNode; translate?: string; 'data-no-translate'?: boolean | string }>(node)) return node;
  if (node.props.translate === 'no' || node.props['data-no-translate']) return node;
  if (node.type !== Fragment && typeof node.type !== 'string') return node;
  if (node.type === 'code' || node.type === 'pre' || node.type === 'script' || node.type === 'style') return node;
  return node.props.children === undefined ? node : cloneElement(node, undefined, translateNode(node.props.children, language));
}

export function useTranslation() {
  const { language, locale } = useAdminPreferences();
  const pluralRules = useMemo(() => new Intl.PluralRules(locale), [locale]);
  const numberFormatter = useMemo(() => new Intl.NumberFormat(locale), [locale]);
  const t = useCallback((text: string, values?: TranslationValues) => {
    const translated = translateText(text, language);
    return values ? translated.replace(/\{(\w+)\}/g, (token, key: string) => values[key] === undefined ? token : String(values[key])) : translated;
  }, [language]);
  const countLabel = useCallback((count: number, singularUIKey: string, pluralUIKey: string) => (
    t(chooseCountUIKey(count, pluralRules, singularUIKey, pluralUIKey))
  ), [pluralRules, t]);
  const formatCount = useCallback((count: number, singularUIKey: string, pluralUIKey: string) => (
    `${numberFormatter.format(count)} ${countLabel(count, singularUIKey, pluralUIKey)}`
  ), [numberFormatter, countLabel]);
  return { t, language, locale, countLabel, formatCount };
}
