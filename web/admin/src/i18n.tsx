function chooseCountUIKey(count: number, rules: Intl.PluralRules, singularUIKey: string, pluralUIKey: string): string {
  return rules.select(count) === 'one' ? singularUIKey : pluralUIKey;
}

const languageKey = 'goby.admin.language';
const themeKey = 'goby.admin.theme';

interface AdminPreferences {
  language: AdminLanguage;
  theme: AdminTheme;
  locale: 'zh-CN' | 'en-US';
  setLanguage: (language: AdminLanguage) => void;
  applyServerLanguage: (culture: string) => void;
  setTheme: (theme: AdminTheme) => void;
  toggleTheme: () => void;
}

function readPreference<T extends string>(key: string, values: readonly T[], fallback: T): T {
  try {
    const saved = window.localStorage.getItem(key);
    return values.includes(saved as T) ? saved as T : fallback;
  } catch {
    return fallback;
  }
}

const PreferencesContext = createContext<AdminPreferences>({
  language: 'zh', theme: 'dark', locale: 'zh-CN',
  setLanguage: () => {}, applyServerLanguage: () => {}, setTheme: () => {}, toggleTheme: () => {},
});

function savedAdminLanguage(): AdminLanguage | undefined {
  try {
    const saved = window.localStorage.getItem(languageKey);
    return saved === 'zh' || saved === 'en' ? saved : undefined;
  } catch {
    return undefined;
  }
}

export function AdminPreferencesProvider({ children }: { children: ReactNode }) {
  const [savedLanguage] = useState(savedAdminLanguage);
  const [language, setLanguageState] = useState<AdminLanguage>(savedLanguage ?? 'zh');
  const explicitLanguage = useRef(savedLanguage !== undefined);
  const serverLanguage = useRef<AdminLanguage>('zh');
  const [theme, setTheme] = useState<AdminTheme>(() => readPreference(themeKey, ['dark', 'light'], 'dark'));
  const setLanguage = useCallback((next: AdminLanguage) => {
    explicitLanguage.current = true;
    document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en';
    setLanguageState(next);
    try { window.localStorage.setItem(languageKey, next); } catch { /* The selected language remains usable for this visit. */ }
  }, []);
  const applyServerLanguage = useCallback((culture: string) => {
    serverLanguage.current = culture === 'en-US' ? 'en' : 'zh';
    if (!explicitLanguage.current) setLanguageState(serverLanguage.current);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
    if (explicitLanguage.current) {
      try { window.localStorage.setItem(languageKey, language); } catch { /* Preferences remain usable when browser storage is unavailable. */ }
    }
  }, [language]);

  useEffect(() => {
    document.documentElement.dataset.theme = theme;
    document.documentElement.style.colorScheme = theme;
    try { window.localStorage.setItem(themeKey, theme); } catch { /* Preferences remain usable when browser storage is unavailable. */ }
  }, [theme]);

  useEffect(() => {
    const changed = (event: StorageEvent) => {
      if (event.key === languageKey) {
        if (event.newValue === 'zh' || event.newValue === 'en') {
          explicitLanguage.current = true;
          setLanguageState(event.newValue);
        } else if (event.newValue === null) {
          explicitLanguage.current = false;
          setLanguageState(serverLanguage.current);
        }
      }
      if (event.key === themeKey && (event.newValue === 'dark' || event.newValue === 'light')) setTheme(event.newValue);
    };
    window.addEventListener('storage', changed);
    return () => window.removeEventListener('storage', changed);
  }, [setLanguage]);

  const toggleTheme = useCallback(() => setTheme((current) => current === 'dark' ? 'light' : 'dark'), []);
  const value = useMemo<AdminPreferences>(() => ({ language, theme, locale: language === 'zh' ? 'zh-CN' : 'en-US', setLanguage, applyServerLanguage, setTheme, toggleTheme }), [language, theme, setLanguage, applyServerLanguage, toggleTheme]);
  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function useAdminPreferences() { return useContext(PreferencesContext); }

