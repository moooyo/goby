func collageTestPNG(t *testing.T, shade color.RGBA) []byte {
	t.Helper()
	canvas := image.NewRGBA(image.Rect(0, 0, 2, 2))
	for y := range 2 {
		for x := range 2 {
			canvas.SetRGBA(x, y, shade)
		}
	}
	var data bytes.Buffer
	if err := png.Encode(&data, canvas); err != nil {
		t.Fatal(err)
	}
	return data.Bytes()
}

func collageTestManifest(t *testing.T, ctx context.Context, store *Store, subject Subject, target ArtworkTarget) *collageManifest {
	t.Helper()
	tx, access, err := store.beginSubjectRead(ctx, subject)
	if err != nil {
		t.Fatal(err)
	}
	defer rollback(tx)
	manifest, err := readCollageManifest(ctx, tx, access, target)
	if err != nil {
		t.Fatal(err)
	}
	return manifest
}

func collageTestOpen(t *testing.T, ctx context.Context, store *Store, subject Subject, itemID string) ([]byte, Image) {
	t.Helper()
	reader, source, err := store.OpenImageContentFor(ctx, subject, itemID, "Primary", 0)
	if err != nil {
		t.Fatal(err)
	}
	defer reader.Close()
	data, err := io.ReadAll(reader)
	if err != nil {
		t.Fatal(err)
	}
	digest := sha256.Sum256(data)
	if source.Source != "generated" || source.ContentDigest() != hex.EncodeToString(digest[:]) || source.Size != int64(len(data)) {
		t.Fatalf("generated bytes do not match their independent content digest: %+v", source)
	}
	return data, source
}

func collageTestGenre(t *testing.T, ctx context.Context, pool *pgxpool.Pool, name string, itemIDs ...string) int64 {
	t.Helper()
	var id int64
	if err := pool.QueryRow(ctx, `INSERT INTO catalog_entities(kind,name) VALUES('Genre',$1) RETURNING id`, name).Scan(&id); err != nil {
		t.Fatal(err)
	}
	for _, itemID := range itemIDs {
		if _, err := pool.Exec(ctx, `INSERT INTO item_entities(item_id,entity_id,position,display_name) VALUES($1,$2,1,$3)`, itemID, id, name); err != nil {
			t.Fatal(err)
		}
	}
	return id
}

func TestCollageSelectsStableFourDistinctSourcesAndTracksSourceVersions(t *testing.T) {
	ctx, pool, store, allowed, user := libraryIntegrationStore(t, &libraryFixtureProber{})
	root := imageStoreTestRoot(t, ctx, pool, store, allowed, "collage-order")
	colors := []color.RGBA{{R: 230, A: 255}, {G: 220, A: 255}, {B: 210, A: 255}, {R: 210, G: 210, A: 255}, {G: 200, B: 200, A: 255}}
	// The duplicate is deliberately sorted between the first and second image.
	for index, id := range []string{"a-first", "c-second", "d-third", "e-fourth", "f-fifth"} {
		imageStoreTestInsert(t, ctx, pool, root, id, "Primary", 0, id+".png", collageTestPNG(t, colors[index]))
	}
	imageStoreTestInsert(t, ctx, pool, root, "b-duplicate", "Primary", 0, "duplicate.png", collageTestPNG(t, colors[0]))
	subject := Subject{UserID: user}
	target := ArtworkTarget{ItemID: root.libraryID}
	manifest := collageTestManifest(t, ctx, store, subject, target)
	var ids []string
	for _, member := range manifest.Members {
		ids = append(ids, member.ItemID)
	}
	if !reflect.DeepEqual(ids, []string{"a-first", "c-second", "d-third", "e-fourth"}) {
		t.Fatalf("unstable or duplicate member selection: %v", ids)
	}
	data, source := collageTestOpen(t, ctx, store, subject, root.libraryID)
	if source.Tag != manifest.Tag {
		t.Fatal("opened collage did not retain its authorized manifest")
	}
	listed, err := store.ListImagesFor(ctx, subject, root.libraryID)
	if err != nil || len(listed) != 1 || listed[0].Tag != manifest.Tag {
		t.Fatalf("image listing diverged from generated source: %+v, %v", listed, err)
	}
	batch, err := store.ImagesForItemsFor(ctx, subject, []string{root.libraryID, root.libraryID})
	if err != nil || len(batch[root.libraryID]) != 1 || batch[root.libraryID][0].Tag != manifest.Tag {
		t.Fatalf("batched collage projection diverged: %+v, %v", batch, err)
	}
	// Identical pixels from a newer source revision must not reuse a manifest.
	if _, err := pool.Exec(ctx, `UPDATE items SET updated_at=updated_at+interval '1 second' WHERE id='a-first'`); err != nil {
		t.Fatal(err)
	}
	repeated, next := collageTestOpen(t, ctx, store, subject, root.libraryID)
	if next.Tag == source.Tag || !bytes.Equal(data, repeated) || next.ContentTag != source.ContentTag {
		t.Fatal("source version and rendered byte identities were conflated")
	}
	if _, err := pool.Exec(ctx, `DELETE FROM items WHERE id='a-first'`); err != nil {
		t.Fatal(err)
	}
	nextManifest := collageTestManifest(t, ctx, store, subject, target)
	if nextManifest.Members[0].ItemID != "b-duplicate" || nextManifest.Tag == next.Tag {
		t.Fatal("source deletion did not regenerate representative selection")
	}
}

func TestCollageGenreUsesOnlyCurrentAuthorizedMembersBeforeCachedPixels(t *testing.T) {
	ctx, pool, store, allowed, user := libraryIntegrationStore(t, &libraryFixtureProber{})
	visible := imageStoreTestRoot(t, ctx, pool, store, allowed, "collage-visible")
	hidden := imageStoreTestRoot(t, ctx, pool, store, allowed, "collage-hidden")
	imageStoreTestInsert(t, ctx, pool, visible, "visible-collage-member", "Primary", 0, "visible.png", collageTestPNG(t, color.RGBA{R: 225, A: 255}))
	imageStoreTestInsert(t, ctx, pool, hidden, "hidden-collage-member", "Primary", 0, "hidden.png", collageTestPNG(t, color.RGBA{B: 225, A: 255}))
	genre := collageTestGenre(t, ctx, pool, "Shared genre", "visible-collage-member", "hidden-collage-member")
	id := strconv.FormatInt(genre, 10)
	_, full := collageTestOpen(t, ctx, store, Subject{UserID: user}, id)
	libraryIntegrationUser(t, ctx, pool, "collage-restricted", false, false, []string{visible.libraryID})
	subject := Subject{UserID: "collage-restricted"}
	data, partial := collageTestOpen(t, ctx, store, subject, id)
	if partial.Tag == full.Tag {
		t.Fatal("different authorized members shared a manifest")
	}
	decoded, err := png.Decode(bytes.NewReader(data))
	if err != nil {
		t.Fatal(err)
	}
	for _, point := range []image.Point{{0, 0}, {511, 511}, {256, 256}} {
		if color.RGBAModel.Convert(decoded.At(point.X, point.Y)) != (color.RGBA{R: 225, A: 255}) {
			t.Fatal("restricted collage exposed hidden member pixels")
		}
	}
	entity, err := store.GetEntityByIDFor(ctx, subject, genre)
	if err != nil || len(entity.Images) != 1 || entity.Images[0].Tag != partial.Tag {
		t.Fatalf("entity DTO uses a different authorization snapshot: %+v, %v", entity, err)
	}
	// Corrupting a hidden root cannot affect selection or reveal its error.
	if _, err := pool.Exec(ctx, `UPDATE library_roots SET path='/unrelated/collage-root' WHERE id=$1`, hidden.id); err != nil {
		t.Fatal(err)
	}
	_, unchanged := collageTestOpen(t, ctx, store, subject, id)
	if unchanged.Tag != partial.Tag {
		t.Fatal("hidden source state changed the visible collage")
	}
	if _, err := pool.Exec(ctx, `UPDATE users SET policy='{"EnableAllFolders":false,"EnabledFolders":[]}'::jsonb WHERE id='collage-restricted'`); err != nil {
		t.Fatal(err)
	}
	if reader, _, err := store.OpenImageContentFor(ctx, subject, id, "Primary", 0); !errors.Is(err, ErrNotFound) {
		if reader != nil {
			reader.Close()
		}
		t.Fatalf("revoked genre survived a populated pixel cache: %v", err)
	}
}

func TestCollageManagedOwnershipSuppressesGenerationAndResetRestoresIt(t *testing.T) {
	ctx, pool, store, allowed, user := libraryIntegrationStore(t, &libraryFixtureProber{})
	root := imageStoreTestRoot(t, ctx, pool, store, allowed, "collage-management")
	actor := metadataEditTestActor(t, ctx, pool, "collage-editor")
	subject := Subject{UserID: user}
	target := ArtworkTarget{ItemID: root.libraryID}
	// An empty library has a deterministic, real rendered placeholder.
	_, placeholder := collageTestOpen(t, ctx, store, subject, root.libraryID)
	before, err := store.GetArtwork(ctx, actor, identity.AdministratorNative, target)
	if err != nil || managedArtworkImage(t, before, "Primary", 0).Tag != placeholder.Tag {
		t.Fatalf("empty generated management source missing: %v", err)
	}
	deleted, err := store.DeleteArtwork(ctx, actor, identity.AdministratorNative, target, before.Revision, "Primary", 0)
	if err != nil || len(deleted.Items) != 0 {
		t.Fatalf("generated deletion did not create a managed tombstone: %+v, %v", deleted, err)
	}
	imageStoreTestInsert(t, ctx, pool, root, "later-member", "Primary", 0, "later.png", collageTestPNG(t, color.RGBA{G: 220, A: 255}))
	if reader, _, err := store.OpenImageContentFor(ctx, subject, root.libraryID, "Primary", 0); !errors.Is(err, ErrNotFound) {
		if reader != nil {
			reader.Close()
		}
		t.Fatalf("new automatic members bypassed the managed tombstone: %v", err)
	}
	if images, err := store.ListImagesFor(ctx, subject, root.libraryID); err != nil || len(images) != 0 {
		t.Fatalf("tombstoned generated source leaked into listing: %+v, %v", images, err)
	}
	reset, err := store.ResetArtwork(ctx, actor, identity.AdministratorNative, target, deleted.Revision, "Primary")
	if err != nil || managedArtworkImage(t, reset, "Primary", 0).Tag == placeholder.Tag {
		t.Fatalf("reset did not select the current member set: %+v, %v", reset, err)
	}
	upload := collageTestPNG(t, color.RGBA{B: 180, A: 255})
	updated, err := store.UploadArtwork(ctx, actor, identity.AdministratorNative, target, reset.Revision, "Primary", 0, upload)
	if err != nil || managedArtworkImage(t, updated, "Primary", 0).Source != "managed" {
		t.Fatalf("managed upload did not override generated pixels: %+v, %v", updated, err)
	}
	reader, image, err := store.OpenImageContentFor(ctx, subject, root.libraryID, "Primary", 0)
	if err != nil {
		t.Fatal(err)
	}
	data, err := io.ReadAll(reader)
	reader.Close()
	if err != nil || image.Source != "managed" || !bytes.Equal(data, upload) {
		t.Fatal("managed bytes lost precedence")
	}
}

func TestCollageChecksChangedPhysicalSourceEvenAfterCaching(t *testing.T) {
	ctx, pool, store, allowed, user := libraryIntegrationStore(t, &libraryFixtureProber{})
	root := imageStoreTestRoot(t, ctx, pool, store, allowed, "collage-source")
	stored := imageStoreTestInsert(t, ctx, pool, root, "collage-source-item", "Primary", 0, "source.png", collageTestPNG(t, color.RGBA{R: 220, A: 255}))
	subject := Subject{UserID: user}
	_, original := collageTestOpen(t, ctx, store, subject, root.libraryID)
	// Concurrent callers may share immutable generated bytes without sharing an
	// authorization decision. Every resulting source must retain one manifest.
	var workers sync.WaitGroup
	for range 8 {
		workers.Go(func() {
			reader, source, err := store.OpenImageContentFor(ctx, subject, root.libraryID, "Primary", 0)
			if err != nil {
				t.Error(err)
				return
			}
			defer reader.Close()
			if source.Tag != original.Tag {
				t.Error("concurrent collage changed its manifest")
			}
		})
	}
	workers.Wait()
	info, err := os.Stat(stored.Path)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(stored.Path, bytes.Repeat([]byte{'x'}, int(info.Size())), 0600); err != nil {
		t.Fatal(err)
	}
	if err := os.Chtimes(stored.Path, time.Now(), info.ModTime()); err != nil {
		t.Fatal(err)
	}
	if reader, _, err := store.OpenImageContentFor(ctx, subject, root.libraryID, "Primary", 0); !errors.Is(err, ErrUnavailable) {
		if reader != nil {
			reader.Close()
		}
		t.Fatalf("same-metadata byte mutation reused cached generated artwork: %v", err)
	}
}

func TestCollageMemberPrecedenceMatchesDirectArtworkAndHonorsTombstones(t *testing.T) {
	ctx, pool, store, allowed, user := libraryIntegrationStore(t, &libraryFixtureProber{})
	root := imageStoreTestRoot(t, ctx, pool, store, allowed, "collage-precedence")
	imageStoreTestInsert(t, ctx, pool, root, "collage-layered", "Primary", 0, "layered.png", collageTestPNG(t, color.RGBA{R: 210, A: 255}))
	subject := Subject{UserID: user}
	target := ArtworkTarget{ItemID: root.libraryID}
	assertSource := func(want string, shade color.RGBA) {
		t.Helper()
		manifest := collageTestManifest(t, ctx, store, subject, target)
		if manifest == nil || len(manifest.Members) != 1 || manifest.Members[0].Source != want {
			t.Fatalf("member source = %+v, want %s", manifest, want)
		}
		data, _ := collageTestOpen(t, ctx, store, subject, root.libraryID)
		decoded, err := png.Decode(bytes.NewReader(data))
		if err != nil {
			t.Fatal(err)
		}
		if color.RGBAModel.Convert(decoded.At(256, 256)) != shade {
			t.Fatalf("%s source did not supply its real pixels", want)
		}
	}
	assertSource("sidecar", color.RGBA{R: 210, A: 255})
	provider := collageTestPNG(t, color.RGBA{B: 200, A: 255})
	digest := sha256.Sum256(provider)
	if _, err := pool.Exec(ctx, `INSERT INTO item_provider_images(item_id,image_type,image_index,provider,provider_id,image_id,content,mime_type,width,height,source_hash)
		VALUES('collage-layered','Primary',0,'tmdb','1','cover',$1,'image/png',2,2,$2)`, provider, hex.EncodeToString(digest[:])); err != nil {
		t.Fatal(err)
	}
	assertSource("provider", color.RGBA{B: 200, A: 255})
	actor := metadataEditTestActor(t, ctx, pool, "collage-layer-editor")
	itemTarget := ArtworkTarget{ItemID: "collage-layered"}
	before, err := store.GetArtwork(ctx, actor, identity.AdministratorNative, itemTarget)
	if err != nil {
		t.Fatal(err)
	}
	uploaded, err := store.UploadArtwork(ctx, actor, identity.AdministratorNative, itemTarget, before.Revision, "Primary", 0, collageTestPNG(t, color.RGBA{G: 190, A: 255}))
	if err != nil {
		t.Fatal(err)
	}
	assertSource("managed", color.RGBA{G: 190, A: 255})
	deleted, err := store.DeleteArtwork(ctx, actor, identity.AdministratorNative, itemTarget, uploaded.Revision, "Primary", 0)
	if err != nil {
		t.Fatal(err)
	}
	manifest := collageTestManifest(t, ctx, store, subject, target)
	if manifest == nil || len(manifest.Members) != 0 {
		t.Fatal("member tombstone fell through to provider or sidecar bytes")
	}
	if _, err := store.ResetArtwork(ctx, actor, identity.AdministratorNative, itemTarget, deleted.Revision, "Primary"); err != nil {
		t.Fatal(err)
	}
	assertSource("provider", color.RGBA{B: 200, A: 255})
	if _, err := pool.Exec(ctx, `DELETE FROM item_provider_images WHERE item_id='collage-layered'`); err != nil {
		t.Fatal(err)
	}
	assertSource("sidecar", color.RGBA{R: 210, A: 255})
}
