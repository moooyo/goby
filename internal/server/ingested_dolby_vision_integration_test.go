func TestIngestedDolbyVisionDefersBackgroundClipWithoutTerminalFailure(t *testing.T) {
	if _, err := exec.LookPath("prlimit"); err != nil {
		t.Skip("prlimit is required by the background clip process runner")
	}
	f, accounts := newClientSessionHTTPAccounts(t)
	root, tools := t.TempDir(), t.TempDir()
	probe, ffmpeg := filepath.Join(tools, "ffprobe"), filepath.Join(tools, "ffmpeg")
	// Synthetic source facts exercise the authorized clip path, not a decoder.
	writeFastIngestFile(t, probe, []byte(`#!/bin/sh
case " $* " in
*" -show_chapters "*) printf '%s\n' '{"format":{"format_name":"mov,mp4","duration":"40","start_time":"0","bit_rate":"800000"},"streams":[{"index":2,"codec_name":"hevc","codec_type":"video","profile":"Main 10","width":320,"height":180,"pix_fmt":"yuv420p10le","time_base":"1/1000","avg_frame_rate":"24/1","field_order":"progressive","side_data_list":[{"side_data_type":"DOVI configuration record","dv_profile":8,"dv_level":6,"rpu_present_flag":1,"el_present_flag":0,"bl_present_flag":1,"dv_bl_signal_compatibility_id":1,"dv_md_compression":"none"}]}]}' ;;
*" -show_entries packet="*)
    IFS= read -r bytes && [ "$bytes" = 'not an MP4' ] || exit 1
    printf 'invalid JSON\n' ;;
*" -show_entries "*) printf '%s\n' '{"streams":[{"index":2,"codec_type":"video","width":320,"height":180,"time_base":"1/1000","sample_aspect_ratio":"1:1"}]}' ;;
' -version ') printf 'ffprobe version 9.0.1-fixture\n';;
*) exit 1;;
esac
`), 0700)
	// Only the strict renderer with the verified in-band trim can emit stdout.
	// Empty stderr and a clean exit let the generated bytes reach MP4 validation.
	writeFastIngestFile(t, ffmpeg, []byte(`#!/bin/sh
case " $* " in
*' -vf trim=start=30.0000000:duration=10.0000000,'*strict_dolbyvision=1:strict_dolbyvision_profile=8*) printf 'not an MP4\n';;
' -version ') printf 'ffmpeg version 9.0.1-fixture\n';;
*) exit 1;;
esac
`), 0700)
	cfg := f.cfg
	cfg.MediaRoots, cfg.FFprobePath, cfg.FFmpegPath, cfg.FastLibraryIngest = []string{root}, probe, ffmpeg, true
	fastIngestReopen(t, f, cfg)
	s := f.app
	if err := s.taskManager.Close(f.ctx); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(root, "Dolby.Vision.mp4")
	writeFastIngestFile(t, path, []byte("declared Dolby Vision source bytes"), 0600)
	collection, err := s.library.CreateLibrary(f.ctx, "Declared Dolby Vision", "movies", []string{root})
	if err != nil {
		t.Fatal(err)
	}
	(&streamHTTPFixture{f: f}).rescan(t, collection.ID)
	item := fastIngestItem(t, f, accounts.viewer.userID, collection.ID, path)
	actor, err := f.users.Resolve(f.ctx, accounts.cookie.Value, "admin")
	if err != nil {
		t.Fatal(err)
	}
	queued, err := s.library.QueueBackgroundPreviews(f.ctx, actor, library.AnalysisSelection{ItemIDs: []string{item.ID}, Force: true}, "pending-dv-preview")
	if err != nil || queued.Queued != 1 {
		t.Fatalf("queue preview: %+v, %v", queued, err)
	}
	sequence := func() int64 {
		t.Helper()
		var value int64
		if err := f.pool.QueryRow(f.ctx, `SELECT sequence FROM task_system_events WHERE name='BackgroundPreviewGenerationRequested'`).Scan(&value); err != nil {
			t.Fatal(err)
		}
		return value
	}
	before := sequence()
	fence := library.AnalysisFence(func(library.OwnedTx) error { return nil })
	claim := func(run, child string) *library.BackgroundPreviewJob {
		t.Helper()
		job, err := s.library.ClaimBackgroundPreview(f.ctx, fence, item.LibraryID, run, child)
		if err != nil {
			t.Fatal(err)
		}
		return job
	}
	job := claim("first-preview-run", "first-preview-child")
	if job == nil || !job.Force {
		t.Fatal("pending verification prevented a first artifact reuse check")
	}
	executor := backgroundPreviewTaskExecutor{server: s}
	if artifact, err := s.library.GenerateBackgroundClip(f.ctx, *job, fence, executor.encode); artifact.Available || !errors.Is(err, errBackgroundPreviewDolbyVisionWaiting) {
		t.Fatalf("pending Dolby Vision did not defer before renderer admission: %+v, %v", artifact, err)
	}
	if err := s.library.DeferBackgroundPreview(f.ctx, fence, *job); err != nil {
		t.Fatal(err)
	}
	if claim("next-preview-run", "next-preview-child") != nil {
		t.Fatal("pending verification immediately reclaimed the same request")
	}
	if err := s.library.RequestBackgroundPreviewContinuation(f.ctx, fence, item.LibraryID); err != nil {
		t.Fatal(err)
	}
	if sequence() != before {
		t.Fatal("a blocked preview emitted its own continuation")
	}
	if detail, err := s.library.GetBackgroundPreviewAsAdministrator(f.ctx, actor, item.ID); err != nil ||
		detail.State != "pending" || detail.RequestedRevision == detail.CompletedRevision {
		t.Fatalf("unverified source burned its preview request: %+v, %v", detail, err)
	}
	preview := f.request(t, http.MethodGet, "/emby/Items/"+item.ID+"/BackgroundPreview", nil, accounts.viewer.headers)
	expectStatus(t, preview, http.StatusOK)
	if jsonObject(t, preview)["Available"] != false {
		t.Fatal("pending verification published a preview artifact")
	}

	// Publish a result only for the source accepted by the completed fast scan.
	tag, err := f.pool.Exec(f.ctx, `UPDATE dolby_vision_verifications SET
		evidence='{"StreamIndex":2,"Verified":true,"Profile":8,"ResidualDisabled":true,"FrameCount":960,"InBandParameterSets":true}',
		verified_at=clock_timestamp(),retry_at='infinity' WHERE item_id=$1 AND evidence IS NULL`, item.ID)
	if err != nil || tag.RowsAffected() != 1 {
		t.Fatalf("publish scoped fixture evidence: %v (%d rows)", err, tag.RowsAffected())
	}
	resumed := claim("ready-preview-run", "ready-preview-child")
	if resumed == nil || resumed.Revision != job.Revision || resumed.OperationID != job.OperationID || !resumed.Force {
		t.Fatalf("verification lost the original preview request: %+v", resumed)
	}
	// Authorize a synthetic device solely for the command contract. No real GPU
	// is used; the declared clip output is intentionally not a valid MP4.
	const device = "/dev/dri/renderD128"
	s.cfg.Transcoding = config.TranscodingConfig{MaxBitrate: config.DefaultMaxBitrate, MaxWidth: config.DefaultMaxWidth,
		MaxHeight: config.DefaultMaxHeight, MaxAudioChannels: config.DefaultMaxAudioChannels,
		Hardware: transcode.Hardware{Decode: "software", Encode: "software", Device: device}}
	s.managedHardware = newManagedHardwareInventoryWithInspector(s.cfg.Transcoding, func(string) (managedHardwareIdentity, string) {
		return managedHardwareTestIdentity(20), ""
	})
	initializeFixtureSettings(t, f)
	cached := acceptedBackgroundDolbyVisionOptions(device)
	s.backgroundPreviews = &backgroundPreviewRuntime{available: true,
		extractor:   media.AnalysisExtractor{FFmpegPath: ffmpeg, FFprobePath: probe},
		dolbyVision: backgroundPreviewDolbyVisionState{options: &cached}}
	artifact, err := s.library.GenerateBackgroundClip(f.ctx, *resumed, fence, executor.encode)
	if artifact.Available || !errors.Is(err, media.ErrAnalysisUnproven) || !strings.Contains(err.Error(), "malformed or duplicate background clip metadata") {
		t.Fatalf("expected verified strict clip to reach MP4 validation without publication: %+v, %v", artifact, err)
	}
}
